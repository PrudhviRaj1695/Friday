package com.friday.app.core

/** Builds the final system instruction from the base prompt, personality, language and user settings. */
object PromptComposer {
    fun compose(
        basePrompt: String,
        personality: PersonalityProfile?,
        language: AppLanguage,
        contentStyle: String,
        customSystemPrompt: String,
        profileDetails: List<String>
    ): String = buildString {
        append(basePrompt.trim())
        append("\n\nRESPONSE LANGUAGE: ")
        append(
            if (language == AppLanguage.TELUGU)
                "Reply in natural, fluent Telugu using Telugu script. Keep code, product names and technical identifiers in English. Do not switch to English unless asked."
            else "Reply in English unless the user explicitly asks for another language."
        )
        append("\nCONTENT STYLE: ")
        append(
            when (contentStyle) {
                "Strict" -> "Keep language formal and clean. Avoid profanity and crude expressions."
                "Relaxed" -> "Use natural, informal language when appropriate. Safety boundaries still apply."
                else -> "Use natural everyday language and avoid unnecessary profanity."
            }
        )
        if (personality != null) {
            append("\nRESPONSE LENGTH: ").append(personality.responseLength.instruction)
            if (personality.systemPrompt.isNotBlank() || personality.tone.isNotBlank()) {
                append("\n\nACTIVE PERSONALITY (").append(personality.name).append("):")
                if (personality.systemPrompt.isNotBlank()) append("\n").append(personality.systemPrompt.trim())
                if (personality.tone.isNotBlank()) append("\nTone: ").append(personality.tone.trim())
            }
        }
        if (customSystemPrompt.isNotBlank()) append("\n\nADDITIONAL USER INSTRUCTIONS:\n").append(customSystemPrompt.trim())
        if (profileDetails.isNotEmpty()) append("\n\nPersonalization profile (user-controlled; follow when relevant):\n").append(profileDetails.joinToString("\n"))
    }

    /** Fixed instruction used by the deterministic "summarize this conversation" command. */
    fun summaryRequest(history: List<Pair<String, String>>, language: AppLanguage): String {
        val transcript = history.takeLast(24).joinToString("\n") { (role, text) ->
            (if (role == "user") "User: " else "FRIDAY: ") + text.take(1200)
        }
        val lang = if (language == AppLanguage.TELUGU) " Write the summary in Telugu." else ""
        return "Summarize the conversation below in a short overview followed by key points and any open action items. Do not add new facts.$lang\n\n--- CONVERSATION ---\n$transcript\n--- END ---"
    }
}

/** Fixed, localized confirmations for deterministic commands (never generated by the LLM). */
object CommandReplies {
    fun language(target: AppLanguage) = when (target) {
        AppLanguage.TELUGU -> "సరే, ఇకపై నేను తెలుగులో మాట్లాడతాను."
        AppLanguage.ENGLISH -> "Okay, I'll reply in English from now on."
    }
    fun personality(name: String, lang: AppLanguage) =
        if (lang == AppLanguage.TELUGU) "$name వ్యక్తిత్వం ఇప్పుడు యాక్టివ్‌గా ఉంది." else "$name personality activated."
    fun personalityNotFound(query: String, available: List<String>, lang: AppLanguage) =
        if (lang == AppLanguage.TELUGU) "\"$query\" అనే వ్యక్తిత్వం దొరకలేదు. అందుబాటులో ఉన్నవి: ${available.joinToString()}."
        else "I couldn't find a personality called \"$query\". Available: ${available.joinToString()}."
    fun temperature(v: Float, lang: AppLanguage) = if (lang == AppLanguage.TELUGU) "టెంపరేచర్ ${fmt(v)} కు సెట్ చేయబడింది." else "Temperature set to ${fmt(v)}."
    fun topP(v: Float, lang: AppLanguage) = if (lang == AppLanguage.TELUGU) "టాప్-P ${fmt(v)} కు సెట్ చేయబడింది." else "Top-p set to ${fmt(v)}."
    fun maxTokens(v: Int, lang: AppLanguage) = if (lang == AppLanguage.TELUGU) "గరిష్ట టోకెన్లు $v." else "Max output tokens set to $v."
    fun voiceMode(mode: VoiceMode, lang: AppLanguage) = if (lang == AppLanguage.TELUGU) "వాయిస్ మోడ్: ${mode.label}." else "Voice mode: ${mode.label}."
    fun backend(b: InferenceBackend, lang: AppLanguage) = if (lang == AppLanguage.TELUGU) "ఇప్పుడు ${b.label} ఉపయోగిస్తున్నాను." else "Now using ${b.label}."
    fun nothingToRepeat(lang: AppLanguage) = if (lang == AppLanguage.TELUGU) "మళ్ళీ చెప్పడానికి ఇంకా సమాధానం లేదు." else "There's no answer to repeat yet."
    fun stopped(lang: AppLanguage) = if (lang == AppLanguage.TELUGU) "సరే, ఆపేశాను." else "Stopped."
    private fun fmt(v: Float) = if (v == v.toInt().toFloat()) v.toInt().toString() else "%.2f".format(java.util.Locale.US, v).trimEnd('0')
}
